/** Resolve a link found in a page against the page's own folder. Null: not a path inside the workspace. */
export function resolveLink(pageDir: string, ref: string): string | null {
  if (!ref || /^([a-z][a-z0-9+.-]*:|\/\/|#)/i.test(ref)) return null;
  const clean = ref.split(/[?#]/)[0];
  if (!clean) return null;
  const parts = (clean.startsWith("/") ? clean.slice(1) : `${pageDir ? `${pageDir}/` : ""}${clean}`).split("/");
  const out: string[] = [];
  for (const p of parts) {
    if (!p || p === ".") continue;
    if (p === "..") {
      if (!out.length) return null;
      out.pop();
    } else {
      try {
        out.push(decodeURIComponent(p));
      } catch {
        out.push(p);
      }
    }
  }
  return out.join("/");
}

export type LinkTarget = { kind: "external" } | { kind: "anchor" } | { kind: "doc"; path: string } | { kind: "file"; path: string };

/** Where a link in a page should go: another page (in the viewer), a file (in the editor), the web, or down the page. */
export function classifyLink(href: string | undefined, pagePath: string, docsDir: string): LinkTarget {
  if (!href) return { kind: "anchor" };
  if (href.startsWith("#")) return { kind: "anchor" };
  const dir = pagePath.includes("/") ? pagePath.slice(0, pagePath.lastIndexOf("/")) : "";
  const rel = resolveLink(dir, href);
  if (rel === null) return { kind: "external" };
  if (/\.(md|mdx|markdown)$/i.test(rel) && (rel === docsDir || rel.startsWith(`${docsDir}/`))) return { kind: "doc", path: rel };
  return { kind: "file", path: rel };
}

/** A page's front matter stripped for display (the viewer shows it in the header instead). */
export function stripFrontMatter(text: string): string {
  const m = /^﻿?---[ \t]*\r?\n[\s\S]*?\r?\n(?:---|\.\.\.)[ \t]*(?:\r?\n|$)/.exec(text);
  return m ? text.slice(m[0].length).replace(/^\s*\n/, "") : text;
}

/**
 * HTML comments (the `<!-- keep -->` markers among them) are for the file's authors: the rendered page does
 * not show them as stray text. Comments inside code fences are code and stay.
 */
export function hideComments(text: string): string {
  const out: string[] = [];
  let fence: string | null = null;
  let inComment = false;
  for (const line of text.split("\n")) {
    const m = /^\s{0,3}(`{3,}|~{3,})/.exec(line);
    if (!inComment && m) {
      if (fence === null) fence = m[1][0];
      else if (m[1][0] === fence) fence = null;
      out.push(line);
      continue;
    }
    if (fence !== null) {
      out.push(line);
      continue;
    }
    let rest = line;
    let kept = "";
    for (;;) {
      if (inComment) {
        const end = rest.indexOf("-->");
        if (end < 0) {
          rest = "";
          break;
        }
        rest = rest.slice(end + 3);
        inComment = false;
      } else {
        const start = rest.indexOf("<!--");
        if (start < 0) break;
        kept += rest.slice(0, start);
        rest = rest.slice(start + 4);
        inComment = true;
      }
    }
    const next = kept + (inComment ? "" : rest);
    // A line that was only a comment leaves nothing behind, not an empty paragraph break.
    if (next.trim() === "" && line.trim() !== "") continue;
    out.push(next);
  }
  return out.join("\n");
}

