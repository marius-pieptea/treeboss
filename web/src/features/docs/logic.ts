export function runSummary(r: RunResult | null | undefined): { pages: number; issues: number; tone: Tone; line: string } {
  if (!r) return { pages: 0, issues: 0, tone: "neutral", line: "Running…" };
  const issues = r.touched.reduce((n, t) => n + t.issues.length, 0) + (r.stray.length ? 1 : 0) + (r.reportedOnly.length ? 1 : 0);
  const pages = r.touched.length;
  const line = pages === 0 ? "Nothing was written" : `${plural(pages, "page")} written${issues ? `, ${plural(issues, "thing")} to check` : ""}`;
  return { pages, issues, tone: pages === 0 ? "neutral" : issues ? "amber" : "green", line };
}

