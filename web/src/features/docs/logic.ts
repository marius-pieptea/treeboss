export interface TreeFolder {
  name: string;
  /** Folder path under the docs dir, "" for the root. */
  path: string;
  folders: TreeFolder[];
  pages: PageInfo[];
}

const byName = (a: string, b: string) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });

/** The pages as nested folders. The index page leads its folder, then pages by title; sub-folders are kept apart. */
export function buildTree(pages: PageInfo[]): TreeFolder {
  const root: TreeFolder = { name: "", path: "", folders: [], pages: [] };
  for (const p of pages) {
    let cur = root;
    let at = "";
    for (const part of p.folder ? p.folder.split("/") : []) {
      at = at ? `${at}/${part}` : part;
      let next = cur.folders.find((f) => f.name === part);
      if (!next) cur.folders.push((next = { name: part, path: at, folders: [], pages: [] }));
      cur = next;
    }
    cur.pages.push(p);
  }
  const sort = (f: TreeFolder) => {
    f.pages.sort((a, b) => (a.kind === "index" ? -1 : b.kind === "index" ? 1 : a.kind === "adr" && b.kind === "adr" ? byName(a.name, b.name) : byName(a.title, b.title)));
    f.folders.sort((a, b) => byName(a.name, b.name));
    f.folders.forEach(sort);
  };
  sort(root);
  return root;
}

/** Pages whose title, path or summary contain every word of the filter. */
export function filterPages(pages: PageInfo[], q: string): PageInfo[] {
  const words = q.toLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return pages;
  return pages.filter((p) => {
    const hay = `${p.title} ${p.path} ${p.summary}`.toLowerCase();
    return words.every((w) => hay.includes(w));
  });
}

