/** A tone the Badge and the dots understand. */
export type Tone = "green" | "amber" | "red" | "neutral";
export const freshnessTone = (f: Freshness): Tone => (f === "fresh" ? "green" : f === "drifting" ? "amber" : f === "stale" ? "red" : "neutral");

/** The dot's colour as a CSS variable, grey for the pages that make no claim. */
export const freshnessColor = (f: Freshness): string => ({ fresh: "var(--green)", drifting: "var(--amber)", stale: "var(--red)", unknown: "var(--fg-faint)", unmanaged: "var(--fg-faint)" })[f];

export const shortSha = (sha: string | null | undefined): string => (sha ? sha.slice(0, 7) : "");

const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;

/** "generated at 1a2b3c4 by claude/opus, 3 commits behind" (the line under the title). */
export function headerLine(page: Pick<PageInfo, "meta">, st: Staleness | null | undefined): string {
  const g = page.meta.generated;
  if (!g?.commit) return page.meta.covers.length ? "Not generated by the app: no commit recorded" : "Not tracked: no commit or covers recorded";
  const parts = [`generated at ${shortSha(g.commit)}${g.by ? ` by ${g.by}` : ""}`];
  if (st) {
    if (st.state === "fresh") parts.push(st.headBehind ? `${plural(st.headBehind, "commit")} since, none touching what it covers` : "current");
    else if (st.state === "unknown") parts.push(st.reason ?? "cannot be checked");
    else if (st.state === "unmanaged") parts.push(st.reason ?? "not tracked");
    else parts.push(`${plural(st.commitsBehind, "commit")} behind, ${plural(st.filesChanged, "covered file")} changed`);
  }
  return parts.join(", ");
}

/** The worst state among pages that can be checked, for the sidebar's summary. */
export function summarize(pages: PageInfo[], staleness: Record<string, Staleness>): { stale: number; drifting: number; fresh: number; untracked: number } {
  const out = { stale: 0, drifting: 0, fresh: 0, untracked: 0 };
  for (const p of pages) {
    const s = staleness[p.path]?.state ?? "unmanaged";
    if (s === "stale") out.stale++;
    else if (s === "drifting") out.drifting++;
    else if (s === "fresh") out.fresh++;
    else out.untracked++;
  }
  return out;
}

