export const compact = (n: number): string => (n >= 1000 ? `${(n / 1000).toFixed(n >= 10_000 ? 0 : 1)}k` : String(n));

export function costTone(tokens: number): "ok" | "warn" | "high" {
  return tokens >= 8000 ? "high" : tokens >= 2500 ? "warn" : "ok";
}

export const attachLabel = (path: string): string => path.replace(/^.*\//, "").replace(/\.(md|mdx|markdown)$/i, "");

/** The next free "0007" after the highest ADR number among the pages (the server has the same rule). */
export function nextAdr(pages: PageInfo[]): string {
  let max = 0;
  for (const p of pages) {
    const m = /^(\d{4})-/.exec(p.name);
    if (p.kind === "adr" && m) max = Math.max(max, Number(m[1]));
  }
  return String(max + 1).padStart(4, "0");
}

export const slug = (s: string): string =>
  s
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);

export const ago = (ms: number | null | undefined): string => {
  if (!ms) return "";
  const s = Math.max(0, Math.round((Date.now() - ms) / 1000));
  if (s < 60) return "just now";
  if (s < 3600) return `${Math.floor(s / 60)}m ago`;
  if (s < 86_400) return `${Math.floor(s / 3600)}h ago`;
  return `${Math.floor(s / 86_400)}d ago`;
};
