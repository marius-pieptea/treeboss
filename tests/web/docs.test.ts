import { describe, expect, test } from "bun:test";
import { attachLabel, buildTree, classifyLink, compact, costTone, filterPages, freshnessColor, freshnessTone, headerLine, hideComments, nextAdr, needsInput, resolveLink, runSummary, shortSha, slug, stripFrontMatter, summarize, type PageInfo, type Staleness } from "../../web/src/features/docs/logic";

const meta = (over: Partial<PageInfo["meta"]> = {}): PageInfo["meta"] => ({ title: null, covers: [], generated: null, status: null, ...over });
const page = (path: string, over: Partial<PageInfo> = {}): PageInfo => {
  const name = path.replace(/^.*\//, "");
  const inner = path.replace(/^docs\//, "");
  return { path, name, folder: inner.includes("/") ? inner.slice(0, inner.lastIndexOf("/")) : "", title: name.replace(/\.md$/, ""), kind: "page", size: 10, mtime: 1, managed: false, meta: meta(), frontMatterError: null, summary: "", ...over };
};
const st = (over: Partial<Staleness> = {}): Staleness => ({ state: "fresh", reason: null, commitsBehind: 0, headBehind: 0, filesChanged: 0, files: [], generatedCommit: "1a2b3c4d5e6f", head: "ffff", ...over });

describe("freshness", () => {
  test("tone and colour per state", () => {
    expect(["fresh", "drifting", "stale", "unknown", "unmanaged"].map((s) => freshnessTone(s as any))).toEqual(["green", "amber", "red", "neutral", "neutral"]);
    expect(freshnessColor("stale")).toBe("var(--red)");
    expect(freshnessColor("unmanaged")).toBe("var(--fg-faint)");
  });

  test("the header line says when, by what, and how far behind", () => {
    const m = meta({ covers: ["src/**"], generated: { commit: "1a2b3c4d5e6f", at: "2026-10-08", by: "claude/opus" } });
    const p = page("docs/a.md", { meta: m });
    expect(headerLine(p, st({ state: "fresh" }))).toBe("generated at 1a2b3c4 by claude/opus, current");
    expect(headerLine(p, st({ state: "fresh", headBehind: 4 }))).toBe("generated at 1a2b3c4 by claude/opus, 4 commits since, none touching what it covers");
    expect(headerLine(p, st({ state: "drifting", commitsBehind: 1, filesChanged: 1 }))).toBe("generated at 1a2b3c4 by claude/opus, 1 commit behind, 1 covered file changed");
    expect(headerLine(p, st({ state: "stale", commitsBehind: 12, filesChanged: 30 }))).toContain("12 commits behind, 30 covered files changed");
    expect(headerLine(p, st({ state: "unknown", reason: "Commit abc is not in this repository" }))).toContain("not in this repository");
    expect(headerLine(page("docs/b.md"), undefined)).toBe("Not tracked: no commit or covers recorded");
    expect(headerLine(page("docs/c.md", { meta: meta({ covers: ["x"] }) }), undefined)).toBe("Not generated by the app: no commit recorded");
    expect(shortSha("1a2b3c4d5e6f")).toBe("1a2b3c4");
    expect(shortSha(null)).toBe("");
  });

  test("the sidebar summary counts what needs work", () => {
    const pages = ["a", "b", "c", "d", "e"].map((n) => page(`docs/${n}.md`));
    const s = Object.fromEntries([["docs/a.md", st({ state: "stale" })], ["docs/b.md", st({ state: "drifting" })], ["docs/c.md", st({ state: "fresh" })], ["docs/d.md", st({ state: "unknown" })]]);
    expect(summarize(pages, s)).toEqual({ stale: 1, drifting: 1, fresh: 1, untracked: 2 });
  });
});

describe("the tree", () => {
  test("pages nest by folder, the index leads, folders come last", () => {
    const pages = [page("docs/zeta.md"), page("docs/index.md", { kind: "index", title: "Home" }), page("docs/guides/setup.md"), page("docs/guides/deep/x.md"), page("docs/alpha.md"), page("docs/decisions/0002-b.md", { kind: "adr" }), page("docs/decisions/0001-a.md", { kind: "adr" })];
    const t = buildTree(pages);
    expect(t.pages.map((p) => p.name)).toEqual(["index.md", "alpha.md", "zeta.md"]);
    expect(t.folders.map((f) => f.name)).toEqual(["decisions", "guides"]);
    expect(t.folders[0].pages.map((p) => p.name)).toEqual(["0001-a.md", "0002-b.md"]);
    expect(t.folders[1].folders[0]).toMatchObject({ name: "deep", path: "guides/deep" });
    expect(t.folders[1].pages.map((p) => p.name)).toEqual(["setup.md"]);
  });

  test("filter by every word, in title, path or summary", () => {
    const pages = [page("docs/architecture.md", { title: "Architecture", summary: "How the daemon fits together" }), page("docs/runbook.md", { title: "Runbook" })];
    expect(filterPages(pages, "").length).toBe(2);
    expect(filterPages(pages, "daemon arch").map((p) => p.name)).toEqual(["architecture.md"]);
    expect(filterPages(pages, "RUNBOOK").map((p) => p.name)).toEqual(["runbook.md"]);
    expect(filterPages(pages, "nothing")).toEqual([]);
  });
});

describe("links inside a page", () => {
  test("relative paths resolve against the page's folder and never leave the workspace", () => {
    expect(resolveLink("docs/guides", "../architecture.md")).toBe("docs/architecture.md");
    expect(resolveLink("docs", "./guides/setup.md#install")).toBe("docs/guides/setup.md");
    expect(resolveLink("docs", "/src/a.ts")).toBe("src/a.ts");
    expect(resolveLink("docs", "../../outside")).toBeNull();
    expect(resolveLink("docs", "https://example.com")).toBeNull();
    expect(resolveLink("docs", "mailto:a@b.c")).toBeNull();
    expect(resolveLink("docs", "#top")).toBeNull();
    expect(resolveLink("docs", "my%20page.md")).toBe("docs/my page.md");
  });

  test("where a link goes: another page, a file, the web, or down the page", () => {
    expect(classifyLink("architecture.md", "docs/index.md", "docs")).toEqual({ kind: "doc", path: "docs/architecture.md" });
    expect(classifyLink("../src/a.ts", "docs/index.md", "docs")).toEqual({ kind: "file", path: "src/a.ts" });
    expect(classifyLink("../README.md", "docs/index.md", "docs")).toEqual({ kind: "file", path: "README.md" });
    expect(classifyLink("https://example.com/x.md", "docs/index.md", "docs")).toEqual({ kind: "external" });
    expect(classifyLink("#section", "docs/index.md", "docs")).toEqual({ kind: "anchor" });
    expect(classifyLink(undefined, "docs/index.md", "docs")).toEqual({ kind: "anchor" });
    expect(classifyLink("x.md", "documentation/manual/index.md", "documentation/manual")).toEqual({ kind: "doc", path: "documentation/manual/x.md" });
  });

  test("front matter is stripped for display and nothing else is", () => {
    expect(stripFrontMatter("---\ntitle: T\n---\n\n# Body\n")).toBe("# Body\n");
    expect(stripFrontMatter("---\r\ntitle: T\r\n---\r\n# Body\r\n")).toBe("# Body\r\n");
    expect(stripFrontMatter("# No block\n\n---\nnot front matter\n---\n")).toBe("# No block\n\n---\nnot front matter\n---\n");
    expect(stripFrontMatter("---\ntitle: T\n---")).toBe("");
  });
});

describe("comments in a page", () => {
  test("html comments, keep markers included, are not shown; code keeps them", () => {
    expect(hideComments("a\n<!-- keep -->\nours\n<!-- /keep -->\nb\n")).toBe("a\nours\nb\n");
    expect(hideComments("text <!-- inline --> more\n")).toBe("text  more\n");
    expect(hideComments("a\n<!--\nmulti\nline\n-->\nb")).toBe("a\nb");
    expect(hideComments("```html\n<!-- keep -->\n```\n")).toBe("```html\n<!-- keep -->\n```\n");
    expect(hideComments("~~~\n<!-- x -->\n~~~\nafter <!-- y -->")).toBe("~~~\n<!-- x -->\n~~~\nafter ");
    expect(hideComments("<!-- unterminated\nstill hidden\n").trim()).toBe("");
    expect(hideComments("no comments\n\n\nkeep blank lines\n")).toBe("no comments\n\n\nkeep blank lines\n");
  });
});

describe("generation", () => {
  test("a run's one-line result", () => {
    expect(runSummary(null)).toMatchObject({ line: "Running…", tone: "neutral" });
    expect(runSummary({ at: "", head: null, touched: [], reportedOnly: [], stray: [] })).toMatchObject({ line: "Nothing was written", tone: "neutral" });
    expect(runSummary({ at: "", head: null, touched: [{ path: "docs/a.md", created: true, issues: [] }], reportedOnly: [], stray: [] })).toMatchObject({ line: "1 page written", tone: "green", issues: 0 });
    const r = runSummary({ at: "", head: null, touched: [{ path: "a", created: false, issues: [{ code: "x", message: "m" }] }, { path: "b", created: false, issues: [] }], reportedOnly: ["c"], stray: ["src/x.ts"] });
    expect(r).toMatchObject({ pages: 2, issues: 3, tone: "amber", line: "2 pages written, 3 things to check" });
  });

  test("which kinds need a topic", () => {
    expect(needsInput("module")).toBe(true);
    expect(needsInput("adr")).toBe(true);
    expect(needsInput("overview")).toBe(false);
    expect(needsInput("refresh")).toBe(false);
  });
});

describe("small formatting", () => {
  test("token counts, cost tone, labels and ADR numbers", () => {
    expect([999, 1000, 15_400, 25_000].map(compact)).toEqual(["999", "1.0k", "15k", "25k"]);
    expect([100, 2500, 8000].map(costTone)).toEqual(["ok", "warn", "high"]);
    expect(attachLabel("docs/guides/setup.md")).toBe("setup");
    expect(slug("Use SQLite, not files!")).toBe("use-sqlite-not-files");
    const adrs = [page("docs/decisions/0001-a.md", { kind: "adr" }), page("docs/decisions/0007-b.md", { kind: "adr" }), page("docs/0099-not-adr.md")];
    expect(nextAdr(adrs)).toBe("0008");
    expect(nextAdr([])).toBe("0001");
  });
});
